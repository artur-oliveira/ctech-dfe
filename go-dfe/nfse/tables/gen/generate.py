#!/usr/bin/env python3
"""Gera as tabelas de referência NFS-e a partir dos anexos e XSDs oficiais.

Uso (a partir da raiz do repositório):
    python3 go-dfe/nfse/tables/gen/generate.py

Entrada:  tmp/anexo_{a,b,c}-*.xlsx, tmp/nfse-esquemas_xsd-*/Schemas/1.01/tiposSimples_v1.01.xsd
Saída:    go-dfe/nfse/tables/{trib_nacional,nbs,indop,enums}.go
          ui/src/lib/data/{nfse_trib_nacional,nfse_nbs,nfse_indop,
          nfse_countries,nfse_enums,nfse_motives}.ts

As saídas são versionadas no repositório; este script não roda em produção.
"""
import glob
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

import openpyxl

XS = "{http://www.w3.org/2001/XMLSchema}"

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
GO_DIR = os.path.join(ROOT, "go-dfe", "nfse", "tables")
UI_DIR = os.path.join(ROOT, "ui", "src", "lib", "data")

HEADER = "// Code generated by nfse/tables/gen/generate.py. DO NOT EDIT.\n\npackage tables\n\n"


def find(pattern):
    # Busca recursiva: os anexos e o pacote de XSDs são descompactados em
    # subpastas de tmp/ que variam por download (tmp/nfse/, tmp/anexos/, ...).
    matches = glob.glob(os.path.join(ROOT, "tmp", pattern)) or glob.glob(
        os.path.join(ROOT, "tmp", "**", pattern), recursive=True)
    if not matches:
        raise SystemExit(f"planilha não encontrada: tmp/{pattern}")
    return sorted(matches)[-1]


def rows(path, sheet):
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True)[sheet]
    it = ws.iter_rows(values_only=True)
    next(it)  # descarta o cabeçalho
    return list(it)


def clean(v):
    return "" if v is None else str(v).replace("\n", " ").strip()


def go_quote(s):
    return json.dumps(s, ensure_ascii=False)


def parse_trib_nacional(path):
    # Coluna A (CÓDIGO DE TRIBUTAÇÃO NACIONAL) é numérica na planilha e perde o zero à
    # esquerda do item quando item < 10 (ex.: item 1/subitem 1/desdobro 1 vira 10101 em
    # vez de 010101). O código oficial (TSCodTribNac no XSD) tem sempre 6 dígitos:
    # item(2) + subitem(2) + desdobro(2). Por isso o código é reconstruído a partir das
    # colunas ITEM/SUBITEM/DESDOBRO, nunca lido diretamente da coluna A.
    out = []
    for row in rows(path, "LISTA.SERV.NAC."):
        if not clean(row[0]):
            continue  # linha de agrupamento (item/subitem sem desdobro)
        item, subitem, desdobro = int(row[1]), int(row[2]), int(row[3])
        code = f"{item:02d}{subitem:02d}{desdobro:02d}"
        out.append({
            "code": code,
            "item": clean(row[1]),
            "subitem": clean(row[2]),
            "desdobro": clean(row[3]),
            "description": clean(row[4]),
        })
    return out


def parse_nbs(path):
    # A aba mistura códigos-folha (9 dígitos sem pontos) com linhas de hierarquia
    # (seção/posição, com menos dígitos) — só os códigos-folha de 9 dígitos são
    # códigos NBS válidos (TSCodNBS no XSD); as linhas de hierarquia são descartadas.
    # A linha "9.9999.99.99" (sem descrição) é o exemplo de formato da planilha, não
    # um código real — todo código NBS real tem descrição preenchida — e é descartada.
    out = []
    for row in rows(path, "LISTA.NBS_v2.0"):
        code = clean(row[0]).replace(".", "")
        description = clean(row[1])
        if len(code) != 9 or not code.isdigit() or not description:
            continue
        out.append({"code": code, "description": description})
    return out


def parse_indop(path):
    # Colunas mescladas: propaga o último valor não-vazio.
    carry = {1: "", 3: "", 7: "", 8: ""}
    out = []
    for row in rows(path, "IndOp"):
        for i in carry:
            v = clean(row[i]) if i < len(row) else ""
            if v:
                carry[i] = v
        code = clean(row[6]) if len(row) > 6 else ""
        if not code:
            continue
        out.append({
            "code": code,
            "tipo_operacao": carry[1],
            "caracteristica_fornecimento": carry[3],
            "local_fornecimento": carry[7],
            "campo_leiaute": carry[8],
        })
    return out


def parse_countries(path):
    out = []
    for row in rows(path, "TAB.PAÍS_ISO2"):
        code, name = clean(row[0]), clean(row[1])
        if len(code) == 2 and name:
            out.append({"code": code, "name": name})
    return out


# Separadores usados entre código e rótulo na documentação do XSD: hífen, travessão,
# meia-risca e parêntese de fechamento (TBMISSQN documenta "1) Isenção").
LABEL_SEPARATORS = r"[-–—)]"

# Enums sem rótulo por código no XSD, cobertos por outra fonte de verdade:
# TSUF já é enum do OpenAPI comum e TSCodigoEventoNFSe vive em nfse/constants.go
# junto das regras de quem pode emitir cada evento.
SKIPPED_ENUMS = ("TSUF", "TSCodigoEventoNFSe")


def enum_documentation(node):
    doc_node = node.find(f"{XS}annotation/{XS}documentation")
    if doc_node is None:
        return ""
    return " ".join("".join(doc_node.itertext()).split())


def labels_by_code(documentation, values):
    """Casa cada rótulo com o código que o XSD enumera, não com a posição.

    A documentação usa separadores e pontuação inconsistentes entre tipos, então
    varrer por posição erra silenciosamente (ex.: TSIdeDedRed usa meia-risca e
    TSVincPrest omite o ponto-e-vírgula do primeiro item). Devolve None quando
    algum código não aparece na documentação — aí o chamador cai no modo posicional.
    """
    starts, pos = [], 0
    for value in values:
        pattern = re.compile(r"(?:^|[;\s(])" + re.escape(value) + r"\s*" + LABEL_SEPARATORS + r"\s*")
        match = pattern.search(documentation, pos)
        if match is None:
            return None
        starts.append((match.end(), match.start()))
        pos = match.end()
    labels = []
    for index, (label_start, _) in enumerate(starts):
        label_end = starts[index + 1][1] if index + 1 < len(starts) else len(documentation)
        labels.append(documentation[label_start:label_end].strip().strip(";.").strip())
    return labels


def labels_by_position(documentation, values):
    """Modo posicional, só para divergência conhecida entre doc e enumeração.

    TSCodJustAnaliseFiscalCanc documenta "3 - Outros" mas enumera value="9". A
    ordem é normativa e estável, então o rótulo é associado pela posição.
    """
    found = [
        match.group(1).strip().strip(";.").strip()
        for match in re.finditer(r"(?:^|[;\s(])\d{1,2}\s*" + LABEL_SEPARATORS + r"\s*([^;]+)", documentation)
    ]
    if len(found) != len(values):
        return None
    return found


def parse_enum_type(root, type_name):
    node = root.find(f"{XS}simpleType[@name='{type_name}']")
    if node is None:
        raise SystemExit(f"tipo XSD não encontrado: {type_name}")
    values = [entry.attrib["value"] for entry in node.findall(f"{XS}restriction/{XS}enumeration")]
    documentation = enum_documentation(node)
    labels = labels_by_code(documentation, values) or labels_by_position(documentation, values)
    if labels is None:
        raise SystemExit(f"rótulos não derivados de {type_name}: {documentation}")
    return [{"value": value, "label": labels[index]} for index, value in enumerate(values)]


def parse_enums(path):
    """Catálogo de todo domínio fechado emitível da DPS/eventos, direto do XSD."""
    root = ET.parse(path).getroot()
    out = {}
    for node in root.findall(f"{XS}simpleType"):
        name = node.get("name")
        if name in SKIPPED_ENUMS or not node.findall(f"{XS}restriction/{XS}enumeration"):
            continue
        out[name] = parse_enum_type(root, name)
    return dict(sorted(out.items()))


def write_go(filename, decl, entries, fields):
    lines = [HEADER, decl, "\n"]
    for e in entries:
        vals = ", ".join(f"{go_field}: {go_quote(e[key])}" for go_field, key in fields)
        lines.append(f'\t{go_quote(e["code"])}: {{{vals}}},\n')
    lines.append("}\n")
    with open(os.path.join(GO_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("".join(lines))
    print(f"{filename}: {len(entries)} entradas")


def write_ts(filename, const_name, ts_type, entry_type_name, entries):
    with open(os.path.join(UI_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("// Code generated by go-dfe/nfse/tables/gen/generate.py. DO NOT EDIT.\n\n")
        fh.write(ts_type + "\n\n")
        fh.write(f"export const {const_name}: readonly {entry_type_name}[] = ")
        fh.write(json.dumps(entries, ensure_ascii=False, indent=2))
        fh.write(" as const;\n")
    print(f"{filename}: {len(entries)} entradas")


def write_enums_go(catalog):
    lines = [HEADER, "var enumTables = map[string][]EnumEntry{\n"]
    for name, entries in catalog.items():
        lines.append(f"\t{go_quote(name)}: {{\n")
        for entry in entries:
            lines.append(f'\t\t{{Value: {go_quote(entry["value"])}, Label: {go_quote(entry["label"])}}},\n')
        lines.append("\t},\n")
    lines.append("}\n")
    with open(os.path.join(GO_DIR, "enums.go"), "w", encoding="utf-8") as fh:
        fh.write("".join(lines))
    print(f"enums.go: {len(catalog)} domínios, {sum(len(v) for v in catalog.values())} entradas")


