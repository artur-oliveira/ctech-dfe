def write_enums_ts(catalog):
    missing = sorted({t for t in TS_ENUM_ALIASES.values() if t not in catalog})
    if missing:
        raise SystemExit(f"alias aponta para tipo inexistente: {missing}")
    filename = "nfse_enums.ts"
    with open(os.path.join(UI_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("// Code generated by go-dfe/nfse/tables/gen/generate.py. DO NOT EDIT.\n\n")
        fh.write("export interface NfseEnumOption { value: string; label: string }\n\n")
        fh.write("/** Catálogo completo dos domínios fechados do XSD, pela chave do tipo. */\n")
        fh.write("export const NFSE_ENUMS: Record<string, readonly NfseEnumOption[]> = ")
        fh.write(json.dumps(catalog, ensure_ascii=False, indent=2))
        fh.write(" as const;\n\n")
        for alias, type_name in TS_ENUM_ALIASES.items():
            fh.write(f"export const {alias}: readonly NfseEnumOption[] = NFSE_ENUMS.{type_name};\n")
    print(f"{filename}: {len(catalog)} domínios, {len(TS_ENUM_ALIASES)} aliases")


def write_motives_ts():
    """nfse_motives.ts virou reexport: o dado vive só em nfse_enums.ts."""
    filename = "nfse_motives.ts"
    with open(os.path.join(UI_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("// Code generated by go-dfe/nfse/tables/gen/generate.py. DO NOT EDIT.\n\n")
        fh.write("// Reexport dos motivos a partir do catálogo único de domínios fechados.\n")
        fh.write("export type { NfseEnumOption as NfseMotiveOption } from './nfse_enums';\n")
        fh.write("export {\n")
        for alias in ("NFSE_THIRD_PARTY_MOTIVES", "NFSE_CANCELLATION_MOTIVES",
                      "NFSE_FISCAL_ANALYSIS_MOTIVES", "NFSE_SUBSTITUTION_MOTIVES",
                      "NFSE_REJECTION_MOTIVES"):
            fh.write(f"  {alias},\n")
        fh.write("} from './nfse_enums';\n")
    print(f"{filename}: reexport")


# Cada seção é independente: o gerador roda só as pedidas na linha de comando
# (`python3 generate.py enums`), porque os anexos e o pacote de XSDs são baixados
# separadamente e nem sempre estão todos em tmp/.
SECTIONS = ("countries", "trib", "nbs", "indop", "enums")


def generate_countries():
    countries = parse_countries(find("anexo_a-*.xlsx"))
    write_ts("nfse_countries.ts", "NFSE_COUNTRIES",
             "export interface NfseCountryEntry {\n  code: string;\n  name: string;\n}",
             "NfseCountryEntry", countries)


def generate_trib():
    trib = parse_trib_nacional(find("anexo_b-*.xlsx"))
    write_go("trib_nacional.go",
             "var tribNacionalTable = map[string]TribNacionalEntry{\n", trib,
             [("Code", "code"), ("Item", "item"), ("Subitem", "subitem"),
              ("Desdobro", "desdobro"), ("Description", "description")])
    write_ts("nfse_trib_nacional.ts", "NFSE_TRIB_NACIONAL",
             "export interface TribNacionalEntry {\n  code: string;\n  item: string;\n"
             "  subitem: string;\n  desdobro: string;\n  description: string;\n}",
             "TribNacionalEntry", trib)


def generate_nbs():
    nbs = parse_nbs(find("anexo_b-*.xlsx"))
    write_go("nbs.go", "var nbsTable = map[string]NBSEntry{\n", nbs,
             [("Code", "code"), ("Description", "description")])
    write_ts("nfse_nbs.ts", "NFSE_NBS",
             "export interface NfseNbsEntry {\n  code: string;\n  description: string;\n}",
             "NfseNbsEntry", nbs)


def generate_indop():
    indop = parse_indop(find("anexo_c-*.xlsx"))
    write_go("indop.go", "var indOpTable = map[string]IndOpEntry{\n", indop,
             [("Code", "code"), ("TipoOperacao", "tipo_operacao"),
              ("CaracteristicaFornecimento", "caracteristica_fornecimento"),
              ("LocalFornecimento", "local_fornecimento"),
              ("CampoLeiaute", "campo_leiaute")])
    write_ts("nfse_indop.ts", "NFSE_INDOP",
             "export interface IndOpEntry {\n  code: string;\n  tipo_operacao: string;\n"
             "  caracteristica_fornecimento: string;\n  local_fornecimento: string;\n"
             "  campo_leiaute: string;\n}",
             "IndOpEntry", indop)


def generate_enums():
    catalog = parse_enums(find("Schemas/1.01/tiposSimples_v1.01.xsd"))
    write_enums_go(catalog)
    write_enums_ts(catalog)
    write_motives_ts()


def main():
    requested = sys.argv[1:] or list(SECTIONS)
    unknown = [name for name in requested if name not in SECTIONS]
    if unknown:
        raise SystemExit(f"seção desconhecida: {unknown}; use uma de {list(SECTIONS)}")
    for name in SECTIONS:
        if name in requested:
            globals()[f"generate_{name}"]()


if __name__ == "__main__":
    main()
