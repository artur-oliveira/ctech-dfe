#!/usr/bin/env python3
"""Gera as tabelas de referência NFS-e a partir dos anexos e XSDs oficiais.

Uso (a partir da raiz do repositório):
    python3 go-dfe/nfse/tables/gen/generate.py

Entrada:  tmp/anexo_{a,b,c}-*.xlsx, tmp/nfse-esquemas_xsd-*/Schemas/1.01/tiposSimples_v1.01.xsd
Saída:    go-dfe/nfse/tables/{trib_nacional,nbs,indop}.go
          ui/src/lib/data/{nfse_trib_nacional,nfse_nbs,nfse_indop,
          nfse_countries,nfse_motives}.ts

As saídas são versionadas no repositório; este script não roda em produção.
"""
import glob
import json
import os
import re
import xml.etree.ElementTree as ET

import openpyxl

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
GO_DIR = os.path.join(ROOT, "go-dfe", "nfse", "tables")
UI_DIR = os.path.join(ROOT, "ui", "src", "lib", "data")

HEADER = "// Code generated by nfse/tables/gen/generate.py. DO NOT EDIT.\n\npackage tables\n\n"


def find(pattern):
    matches = glob.glob(os.path.join(ROOT, "tmp", pattern))
    if not matches:
        raise SystemExit(f"planilha não encontrada: tmp/{pattern}")
    return sorted(matches)[-1]


def rows(path, sheet):
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True)[sheet]
    it = ws.iter_rows(values_only=True)
    next(it)  # descarta o cabeçalho
    return list(it)


def clean(v):
    return "" if v is None else str(v).replace("\n", " ").strip()


def go_quote(s):
    return json.dumps(s, ensure_ascii=False)


def parse_trib_nacional(path):
    # Coluna A (CÓDIGO DE TRIBUTAÇÃO NACIONAL) é numérica na planilha e perde o zero à
    # esquerda do item quando item < 10 (ex.: item 1/subitem 1/desdobro 1 vira 10101 em
    # vez de 010101). O código oficial (TSCodTribNac no XSD) tem sempre 6 dígitos:
    # item(2) + subitem(2) + desdobro(2). Por isso o código é reconstruído a partir das
    # colunas ITEM/SUBITEM/DESDOBRO, nunca lido diretamente da coluna A.
    out = []
    for row in rows(path, "LISTA.SERV.NAC."):
        if not clean(row[0]):
            continue  # linha de agrupamento (item/subitem sem desdobro)
        item, subitem, desdobro = int(row[1]), int(row[2]), int(row[3])
        code = f"{item:02d}{subitem:02d}{desdobro:02d}"
        out.append({
            "code": code,
            "item": clean(row[1]),
            "subitem": clean(row[2]),
            "desdobro": clean(row[3]),
            "description": clean(row[4]),
        })
    return out


def parse_nbs(path):
    # A aba mistura códigos-folha (9 dígitos sem pontos) com linhas de hierarquia
    # (seção/posição, com menos dígitos) — só os códigos-folha de 9 dígitos são
    # códigos NBS válidos (TSCodNBS no XSD); as linhas de hierarquia são descartadas.
    # A linha "9.9999.99.99" (sem descrição) é o exemplo de formato da planilha, não
    # um código real — todo código NBS real tem descrição preenchida — e é descartada.
    out = []
    for row in rows(path, "LISTA.NBS_v2.0"):
        code = clean(row[0]).replace(".", "")
        description = clean(row[1])
        if len(code) != 9 or not code.isdigit() or not description:
            continue
        out.append({"code": code, "description": description})
    return out


def parse_indop(path):
    # Colunas mescladas: propaga o último valor não-vazio.
    carry = {1: "", 3: "", 7: "", 8: ""}
    out = []
    for row in rows(path, "IndOp"):
        for i in carry:
            v = clean(row[i]) if i < len(row) else ""
            if v:
                carry[i] = v
        code = clean(row[6]) if len(row) > 6 else ""
        if not code:
            continue
        out.append({
            "code": code,
            "tipo_operacao": carry[1],
            "caracteristica_fornecimento": carry[3],
            "local_fornecimento": carry[7],
            "campo_leiaute": carry[8],
        })
    return out


def parse_countries(path):
    out = []
    for row in rows(path, "TAB.PAÍS_ISO2"):
        code, name = clean(row[0]), clean(row[1])
        if len(code) == 2 and name:
            out.append({"code": code, "name": name})
    return out


def parse_motive_type(root, type_name):
    ns = {"xs": "http://www.w3.org/2001/XMLSchema"}
    node = root.find(f"xs:simpleType[@name='{type_name}']", ns)
    if node is None:
        raise SystemExit(f"tipo XSD não encontrado: {type_name}")
    doc_node = node.find("xs:annotation/xs:documentation", ns)
    documentation = " ".join("".join(doc_node.itertext()).split())
    values = [entry.attrib["value"] for entry in node.findall("xs:restriction/xs:enumeration", ns)]
    # A documentação e a enumeração oficial divergem em um ponto conhecido:
    # TSCodJustAnaliseFiscalCanc descreve "3 - Outros", mas enumera value="9".
    # A ordem é normativa e estável, então associamos os rótulos aos enums por posição.
    labels = [
        match.group(1).strip().rstrip('.')
        for match in re.finditer(r"(?:^|[:;])\s*\d{1,2}\s*-\s*([^;]+)", documentation)
    ]
    return [
        {"value": value, "label": labels[index] if index < len(labels) else value}
        for index, value in enumerate(values)
    ]


def parse_motives(path):
    root = ET.parse(path).getroot()
    return {
        "emit_third_party": parse_motive_type(root, "TSMotivoEmisTI"),
        "cancellation": parse_motive_type(root, "TSCodJustCanc"),
        "fiscal_analysis": parse_motive_type(root, "TSCodJustAnaliseFiscalCanc"),
        "substitution": parse_motive_type(root, "TSCodJustSubst"),
        "rejection": parse_motive_type(root, "TSCodMotivoRejeicao"),
    }


def write_go(filename, decl, entries, fields):
    lines = [HEADER, decl, "\n"]
    for e in entries:
        vals = ", ".join(f"{go_field}: {go_quote(e[key])}" for go_field, key in fields)
        lines.append(f'\t{go_quote(e["code"])}: {{{vals}}},\n')
    lines.append("}\n")
    with open(os.path.join(GO_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("".join(lines))
    print(f"{filename}: {len(entries)} entradas")


def write_ts(filename, const_name, ts_type, entry_type_name, entries):
    with open(os.path.join(UI_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("// Code generated by go-dfe/nfse/tables/gen/generate.py. DO NOT EDIT.\n\n")
        fh.write(ts_type + "\n\n")
        fh.write(f"export const {const_name}: readonly {entry_type_name}[] = ")
        fh.write(json.dumps(entries, ensure_ascii=False, indent=2))
        fh.write(" as const;\n")
    print(f"{filename}: {len(entries)} entradas")


def write_motives(entries):
    filename = "nfse_motives.ts"
    names = {
        "emit_third_party": "NFSE_THIRD_PARTY_MOTIVES",
        "cancellation": "NFSE_CANCELLATION_MOTIVES",
        "fiscal_analysis": "NFSE_FISCAL_ANALYSIS_MOTIVES",
        "substitution": "NFSE_SUBSTITUTION_MOTIVES",
        "rejection": "NFSE_REJECTION_MOTIVES",
    }
    with open(os.path.join(UI_DIR, filename), "w", encoding="utf-8") as fh:
        fh.write("// Code generated by go-dfe/nfse/tables/gen/generate.py. DO NOT EDIT.\n\n")
        fh.write("export interface NfseMotiveOption { value: string; label: string }\n\n")
        for key, const_name in names.items():
            fh.write(f"export const {const_name}: readonly NfseMotiveOption[] = ")
            fh.write(json.dumps(entries[key], ensure_ascii=False, indent=2))
            fh.write(" as const;\n\n")
    print(f"{filename}: {sum(len(v) for v in entries.values())} entradas")


def main():
    anexo_a = find("anexo_a-*.xlsx")
    anexo_b = find("anexo_b-*.xlsx")
    anexo_c = find("anexo_c-*.xlsx")
    tipos_simples = find("nfse-esquemas_xsd-*/Schemas/1.01/tiposSimples_v1.01.xsd")

    countries = parse_countries(anexo_a)
    trib = parse_trib_nacional(anexo_b)
    nbs = parse_nbs(anexo_b)
    indop = parse_indop(anexo_c)
    motives = parse_motives(tipos_simples)

    write_go("trib_nacional.go",
             "var tribNacionalTable = map[string]TribNacionalEntry{\n", trib,
             [("Code", "code"), ("Item", "item"), ("Subitem", "subitem"),
              ("Desdobro", "desdobro"), ("Description", "description")])
    write_go("nbs.go",
             "var nbsTable = map[string]NBSEntry{\n", nbs,
             [("Code", "code"), ("Description", "description")])
    write_go("indop.go",
             "var indOpTable = map[string]IndOpEntry{\n", indop,
             [("Code", "code"), ("TipoOperacao", "tipo_operacao"),
              ("CaracteristicaFornecimento", "caracteristica_fornecimento"),
              ("LocalFornecimento", "local_fornecimento"),
              ("CampoLeiaute", "campo_leiaute")])

    write_ts("nfse_trib_nacional.ts", "NFSE_TRIB_NACIONAL",
             "export interface TribNacionalEntry {\n  code: string;\n  item: string;\n"
             "  subitem: string;\n  desdobro: string;\n  description: string;\n}",
             "TribNacionalEntry", trib)
    write_ts("nfse_nbs.ts", "NFSE_NBS",
             "export interface NfseNbsEntry {\n  code: string;\n  description: string;\n}",
             "NfseNbsEntry", nbs)
    write_ts("nfse_indop.ts", "NFSE_INDOP",
             "export interface IndOpEntry {\n  code: string;\n  tipo_operacao: string;\n"
             "  caracteristica_fornecimento: string;\n  local_fornecimento: string;\n"
             "  campo_leiaute: string;\n}",
             "IndOpEntry", indop)
    write_ts("nfse_countries.ts", "NFSE_COUNTRIES",
             "export interface NfseCountryEntry {\n  code: string;\n  name: string;\n}",
             "NfseCountryEntry", countries)
    write_motives(motives)


if __name__ == "__main__":
    main()
