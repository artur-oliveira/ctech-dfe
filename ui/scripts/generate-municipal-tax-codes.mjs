// Gera src/lib/data/municipal_tax_codes_data.ts a partir das tabelas de ISS de
// https://contabilidade.com/tabela-iss/ (sitemap + __NEXT_DATA__ de cada cidade).
// Uso: node scripts/generate-municipal-tax-codes.mjs [saida]
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const SITEMAP_URL = 'https://contabilidade.com/sitemap-tabela-iss.xml';
const CITY_URL_PATTERN = /<loc>(https:\/\/contabilidade\.com\/tabela-iss\/[^/]+\/[^/]+-[a-z]{2}\/)<\/loc>/g;
const NEXT_DATA_PATTERN = /<script id="__NEXT_DATA__"[^>]*>(.*?)<\/script>/s;
const REQUEST_DELAY_MS = 1500;
const USER_AGENT = 'ctech-dfe-catalog-generator';
const DEFAULT_OUTPUT = 'src/lib/data/municipal_tax_codes_data.ts';

const outputPath = resolve(process.cwd(), process.argv[2] ?? DEFAULT_OUTPUT);
const sleep = (ms) => new Promise((done) => setTimeout(done, ms));
const get = async (url) => {
  const res = await fetch(url, {headers: {'user-agent': USER_AGENT}});
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
};
const parseRate = (raw) => {
  const rate = Number.parseFloat(String(raw).replace('%', '').replace(',', '.'));
  return Number.isFinite(rate) ? rate : null;
};

const urls = [...(await get(SITEMAP_URL)).matchAll(CITY_URL_PATTERN)].map((m) => m[1]);
const catalog = {};
const skipped = [];
for (const url of urls) {
  try {
    const match = NEXT_DATA_PATTERN.exec(await get(url));
    const {info, data} = JSON.parse(match[1]).props.pageProps.pageTableISS;
    if (!/^\d{7}$/.test(info.codigo_ibge) || !data?.length) throw new Error('sem IBGE ou tabela vazia');
    catalog[info.codigo_ibge] = data.filter((row) => row.codigo_servico?.trim()).map((row) => [row.lei_116, row.codigo_servico.trim(), parseRate(row.aliquota)]);
    console.log(`${info.codigo_ibge} ${info.cidade}-${info.estado}: ${data.length}`);
  } catch (err) {
    skipped.push(`${url}: ${err.message}`);
  }
  await sleep(REQUEST_DELAY_MS);
}

const ibges = Object.keys(catalog).sort();
const body = ibges.map((ibge) => `  "${ibge}": ${JSON.stringify(catalog[ibge])},`).join('\n');
writeFileSync(outputPath, `// Code generated by scripts/generate-municipal-tax-codes.mjs. DO NOT EDIT.
// Fonte: https://contabilidade.com/tabela-iss/ (códigos de serviço da lei municipal).
// Linha: [item LC 116 (NN.NN), código municipal, alíquota ISS em % ou null].

export type MunicipalTaxRow = readonly [string, string, number | null]

export const MUNICIPAL_TAX_CATALOG: Readonly<Record<string, readonly MunicipalTaxRow[]>> = {
${body}
};
`);
console.log(`${ibges.length} municípios; ${skipped.length} ignorados`);
skipped.forEach((s) => console.warn(s));
