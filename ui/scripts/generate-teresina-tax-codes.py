#!/usr/bin/env python3
"""Gera src/lib/data/teresina_tax_codes_data.ts a partir da planilha oficial da SEMF de Teresina
("Correspondencia CNAE Codigo Tributacao.xlsx"). Só biblioteca padrão.
Uso: python3 -I scripts/generate-teresina-tax-codes.py <planilha.xlsx> [saida]

Código completo NN.NN.NN.NNN: cTribNac = 3 primeiros segmentos (6 dígitos), cTribMun = 4º segmento (3 dígitos).
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
DEFAULT_OUTPUT = 'src/lib/data/teresina_tax_codes_data.ts'
FULL_CODE = re.compile(r'^(\d\d)\.(\d\d)\.(\d\d)\.(\d{3})$')


def text(si):
    return ''.join(t.text or '' for t in si.iter(NS + 't'))


def read_rows(path):
    z = zipfile.ZipFile(path)
    shared = [text(si) for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(NS + 'si')]
    for row in ET.fromstring(z.read('xl/worksheets/sheet1.xml')).iter(NS + 'row'):
        cells = {}
        for c in row.findall(NS + 'c'):
            v = c.find(NS + 'v')
            if v is not None:
                cells[re.sub(r'\d', '', c.get('r'))] = shared[int(v.text)] if c.get('t') == 's' else v.text
        yield cells


rows, seen = [], set()
for cells in read_rows(sys.argv[1]):
    m = FULL_CODE.match(cells.get('A', '').strip())
    if not m:
        continue  # cabeçalho
    nac, mun = ''.join(m.groups()[:3]), m.group(4)
    assert (nac, mun) not in seen, f'duplicado {nac}/{mun}'
    seen.add((nac, mun))
    rows.append([nac, mun, float(cells['E']), ' '.join(cells.get('C', '').split())])

out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUTPUT
body = ',\n'.join('  ' + __import__('json').dumps(r, ensure_ascii=False) for r in rows)
open(out, 'w', encoding='utf-8').write(f'''// Code generated by scripts/generate-teresina-tax-codes.py. DO NOT EDIT.
// Fonte: planilha oficial da SEMF de Teresina (Correspondência CNAE x Código de Tributação).
// Linha: [cTribNac (6 dígitos), cTribMun (3 dígitos), alíquota ISS em %, descrição].

export type TeresinaTaxRow = readonly [string, string, number, string]

export const TERESINA_TAX_ROWS: readonly TeresinaTaxRow[] = [
{body},
];
''')
print(len(rows), 'linhas')
